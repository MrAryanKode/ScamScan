# ---------------------------------------------------------
# ScamScan Findings Service
# ---------------------------------------------------------
#
# This file converts numerical forensic analysis results
# into simple human-readable findings.
#
# The findings are indicators only.
# They do NOT prove that an image is genuine or forged.
# ---------------------------------------------------------


# ---------------------------------------------------------
# MAIN FINDINGS FUNCTION
# ---------------------------------------------------------
#
# scan.py calls this function using:
#
# generate_forensic_findings(
#     risk_result,
#     ocr_result
# )
#
# Therefore this function must exist with this exact name.
# ---------------------------------------------------------

def generate_forensic_findings(
    risk_result: dict,
    ocr_result: dict
) -> list:
    """
    Generate human-readable forensic findings.

    Parameters
    ----------
    risk_result:
        Complete preliminary forensic risk result.

    ocr_result:
        OCR result generated by Tesseract.

    Returns
    -------
    list:
        Human-readable forensic findings.
    """

    # -----------------------------------------------------
    # Extract risk score
    # -----------------------------------------------------

    risk_score = risk_result.get(
        "risk_score",
        0
    )

    # -----------------------------------------------------
    # Extract risk level
    # -----------------------------------------------------

    risk_level = risk_result.get(
        "risk_level",
        "Unknown"
    )

    # -----------------------------------------------------
    # Extract ELA information
    # -----------------------------------------------------

    ela_analysis = risk_result.get(
        "ela_analysis",
        {}
    )

    ela_score = ela_analysis.get(
        "ela_score",
        0
    )

    # -----------------------------------------------------
    # Extract edge information
    # -----------------------------------------------------

    edge_analysis = risk_result.get(
        "edge_analysis",
        {}
    )

    edge_score = edge_analysis.get(
        "edge_score",
        0
    )

    edge_density = edge_analysis.get(
        "edge_density",
        0
    )

    # -----------------------------------------------------
    # Extract heatmap information
    # -----------------------------------------------------

    heatmap_analysis = risk_result.get(
        "heatmap_analysis",
        {}
    )

    heatmap_score = heatmap_analysis.get(
        "heatmap_score",
        0
    )

    high_activity_ratio = heatmap_analysis.get(
        "high_activity_ratio",
        0
    )

    # -----------------------------------------------------
    # Extract OCR text
    # -----------------------------------------------------

    ocr_text = ocr_result.get(
        "text",
        ""
    )

    # -----------------------------------------------------
    # Calculate OCR text length
    # -----------------------------------------------------
    #
    # We use the actual text as a fallback because older
    # OCR results may not contain character_count.
    # -----------------------------------------------------

    ocr_text_length = ocr_result.get(
        "character_count",
        len(ocr_text)
    )

    # -----------------------------------------------------
    # Create findings list
    # -----------------------------------------------------

    findings = []

    # =====================================================
    # ELA FINDING
    # =====================================================

    if ela_score >= 60:

        findings.append(
            "Strong compression differences were detected "
            "and require further investigation."
        )

    elif ela_score >= 30:

        findings.append(
            "Moderate compression differences were detected."
        )

    else:

        findings.append(
            "No major compression anomaly detected."
        )

    # =====================================================
    # EDGE FINDING
    # =====================================================

    if edge_score >= 70:

        findings.append(
            "High edge activity was detected in the image "
            "and some regions may require investigation."
        )

    elif edge_score >= 40:

        findings.append(
            "Moderate edge activity was detected."
        )

    else:

        findings.append(
            "Edge activity is within a relatively normal range."
        )

    # =====================================================
    # HEATMAP FINDING
    # =====================================================

    if heatmap_score >= 70:

        findings.append(
            "High-activity regions were detected in the "
            "generated forensic heatmap."
        )

    elif heatmap_score >= 40:

        findings.append(
            "Some elevated activity was detected in the "
            "forensic heatmap."
        )

    else:

        findings.append(
            "No major high-activity region detected."
        )

    # =====================================================
    # OCR FINDING
    # =====================================================

    if ocr_text_length > 0:

        findings.append(
            f"OCR detected readable text "
            f"({ocr_text_length} characters)."
        )

    else:

        findings.append(
            "No readable text was detected by OCR."
        )

    # =====================================================
    # RISK FINDING
    # =====================================================
    #
    # This provides a simple explanation of the overall
    # preliminary risk result.
    # =====================================================

    if risk_score >= 70:

        findings.append(
            "The combined forensic indicators produce "
            "a high preliminary risk score."
        )

    elif risk_score >= 40:

        findings.append(
            "The combined forensic indicators produce "
            "a moderate preliminary risk score."
        )

    else:

        findings.append(
            "The combined forensic indicators produce "
            "a low preliminary risk score."
        )

    # =====================================================
    # IMPORTANT DISCLAIMER
    # =====================================================
    #
    # Never present these techniques as absolute proof.
    # ELA, edges, heatmaps and OCR are investigative clues.
    # =====================================================

    findings.append(
        "These findings are forensic indicators and do not "
        "prove that the image is genuine or forged."
    )

    # Return all generated findings.

    return findings


# ---------------------------------------------------------
# BACKWARD-COMPATIBILITY FUNCTION
# ---------------------------------------------------------
#
# Older versions of scan.py used:
#
# generate_findings(
#     ela_score=...,
#     edge_score=...,
#     heatmap_score=...,
#     ocr_text_length=...
# )
#
# We keep this function so older code does not break.
# ---------------------------------------------------------

def generate_findings(
    ela_score: float = 0,
    edge_score: float = 0,
    heatmap_score: float = 0,
    ocr_text_length: int = 0
) -> list:
    """
    Backward-compatible findings generator.

    This function is kept for older versions of ScamScan.
    """

    # Create a risk result in the same structure used
    # by the newer findings function.

    risk_result = {

        "risk_score": (
            ela_score * 0.3
            + edge_score * 0.4
            + heatmap_score * 0.3
        ),

        "risk_level": "Preliminary",

        "ela_analysis": {
            "ela_score": ela_score
        },

        "edge_analysis": {
            "edge_score": edge_score
        },

        "heatmap_analysis": {
            "heatmap_score": heatmap_score
        }
    }

    # Create OCR result compatible with the main function.

    ocr_result = {

        "text": "x" * max(
            0,
            int(ocr_text_length)
        ),

        "character_count": max(
            0,
            int(ocr_text_length)
        )
    }

    # Reuse the main findings logic.

    return generate_forensic_findings(
        risk_result,
        ocr_result
    )